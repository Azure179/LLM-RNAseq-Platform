"""One deterministic mapping for domain/LLM errors; does not exercise network or R."""

import pytest
from bulk_rnaseq.api.errors import http_error


@pytest.mark.parametrize("code,status,public", [
    ("PROJECT_NOT_FOUND", 404, "PROJECT_NOT_FOUND"), ("UNKNOWN_SKILL", 404, "SKILL_NOT_FOUND"),
    ("RUN_NOT_FOUND", 404, "RESULT_NOT_FOUND"), ("ARTIFACT_NOT_FOUND", 404, "ARTIFACT_NOT_FOUND"),
    ("INVALID_PARAMETER", 422, "INVALID_PARAMETER"), ("FORBIDDEN_PARAMETER", 422, "FORBIDDEN_PARAMETER"),
    ("UNKNOWN_PARAMETER", 422, "UNKNOWN_PARAMETER"), ("IDENTICAL_GROUPS", 422, "INVALID_COMPARISON"),
    ("NON_INTEGER_COUNT", 422, "INPUT_VALIDATION_FAILED"),
    ("INVALID_WORKFLOW_PLAN", 422, "INVALID_WORKFLOW_PLAN"),
    ("INVALID_CUSTOMIZATION_PLAN", 422, "INVALID_CUSTOMIZATION_PLAN"),
    ("WORKFLOW_CYCLE_DETECTED", 422, "WORKFLOW_CYCLE_DETECTED"),
    ("INVALID_OUTPUT_BINDING", 422, "INVALID_OUTPUT_BINDING"),
    ("MISSING_PROJECT_INPUT", 409, "MISSING_PROJECT_INPUT"),
    ("MISSING_UPSTREAM_DEPENDENCY", 409, "MISSING_UPSTREAM_DEPENDENCY"),
    ("AMBIGUOUS_UPSTREAM_RESULT", 409, "AMBIGUOUS_UPSTREAM_RESULT"),
    ("CHAT_BUSY", 409, "PROJECT_BUSY"), ("RSCRIPT_FAILED", 502, "RSCRIPT_FAILED"),
    ("LLM_RESPONSE_VALIDATION_FAILED", 502, "LLM_RESPONSE_VALIDATION_FAILED"),
    ("LLM_NETWORK_ERROR", 503, "LLM_NETWORK_ERROR"), ("LLM_TIMEOUT", 504, "LLM_TIMEOUT"),
    ("PRIVATE_CODE", 500, "INTERNAL_SERVER_ERROR"), (None, 500, "INTERNAL_SERVER_ERROR"),
])
def test_mapping(code, status, public):
    assert http_error(code) == (status, public)
